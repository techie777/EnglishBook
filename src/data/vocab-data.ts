// Helper functions for retrieval
export function getAllVocab(): VocabWord[] {
  return VOCAB_WORDS;
}

export function getVocabByCategory(category: VocabCategory): VocabWord[] {
  return VOCAB_WORDS.filter((w) => w.category === category);
}

export function getVocabById(id: string): VocabWord | undefined {
  return VOCAB_WORDS.find((w) => w.id === id || w.word.toLowerCase() === id.toLowerCase());
}

export function getVocabByCategoryAndWord(category: string, wordId: string): VocabWord | undefined {
  return VOCAB_WORDS.find(
    (w) => w.category === category && (w.id === wordId || w.word.toLowerCase() === wordId.toLowerCase())
  );
}

export function getVocabByLevel(level: string): VocabWord[] {
  return VOCAB_WORDS.filter((w) => w.level === level);
}
