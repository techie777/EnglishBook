export function getSentencesByDay(day: number): DailySentence[] {
  return DAILY_SENTENCES.filter((s) => s.day === day);
}

export function getAllDays(): { day: number; title: string; count: number }[] {
  const daysMap = new Map<number, { title: string; count: number }>();
  DAILY_SENTENCES.forEach((s) => {
    if (!daysMap.has(s.day)) {
      daysMap.set(s.day, { title: s.dayTitle, count: 1 });
    } else {
      const cur = daysMap.get(s.day)!;
      cur.count += 1;
    }
  });

  return Array.from(daysMap.entries()).map(([day, val]) => ({
    day,
    title: val.title,
    count: val.count,
  }));
}
